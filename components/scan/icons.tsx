import { IconAlertTriangle, IconShieldCheck } from "@/components/audit/icons";

// Resolves the mock's icon names (stored verbatim in scanRules data) to
// components. Falls back to the file-check mark for anything unmapped.
const BY_NAME: Record<string, (props: IconProps) => React.JSX.Element> = {
  "map-pin": IconMapPin,
  users: IconUsers,
  wallet: IconWallet,
  heartbeat: IconHeartPulse,
  "user-plus": IconUserPlus,
  building: IconBuilding,
  clock: IconClock,
  "alert-triangle": IconAlertTriangle,
  "shield-check": IconShieldCheck,
  "file-check": IconFileCheck,
  coin: IconCoins,
  sparkles: IconSparkles,
};

export function ScanIcon({ name, ...props }: IconProps & { name: string }) {
  const Cmp = BY_NAME[name] ?? IconFileCheck;
  return <Cmp {...props} />;
}
